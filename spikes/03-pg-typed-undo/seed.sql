-- Spike seed, run as mulligan_gw so it owns every table. Deterministic values, with
-- awkward ones on purpose: microsecond timestamps with offsets, 0.1 + 0.2, NaN and
-- Infinity floats, numeric scale, unicode and quotes in text and jsonb, arrays.

CREATE TABLE customers (
  id         integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  email      text NOT NULL UNIQUE,
  name       text NOT NULL,
  active     boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL,
  meta       jsonb
);

CREATE TABLE products (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku        text NOT NULL UNIQUE,
  name       text NOT NULL,
  price      numeric(10,2) NOT NULL,
  weight_kg  double precision,
  tags       text[],
  attrs      jsonb,
  updated_at timestamp
);

CREATE TABLE orders (
  id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  placed_at   timestamptz NOT NULL,
  note        text
);

CREATE TABLE order_items (
  order_id   bigint  NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  line_no    integer NOT NULL,
  product_id integer NOT NULL REFERENCES products(id),
  qty        integer NOT NULL,
  unit_price numeric(10,2) NOT NULL,
  line_total numeric(12,2) GENERATED ALWAYS AS (qty * unit_price) STORED,
  PRIMARY KEY (order_id, line_no)
);

CREATE TABLE support_tickets (
  id          serial PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  subject     text NOT NULL,
  opened_on   date NOT NULL
);

CREATE TABLE customer_notes (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_id integer REFERENCES customers(id) ON DELETE SET NULL,
  body        text NOT NULL
);

CREATE TABLE employees (
  id         integer PRIMARY KEY,
  name       text NOT NULL,
  manager_id integer REFERENCES employees(id) ON DELETE CASCADE
);

CREATE TABLE legacy_pricing (
  id         integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES products(id),
  region     text NOT NULL,
  price      numeric(10,2) NOT NULL,
  UNIQUE (product_id, region)
);
CREATE INDEX legacy_pricing_region_idx ON legacy_pricing (region);

CREATE TABLE price_overrides (
  id                integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  legacy_pricing_id integer NOT NULL REFERENCES legacy_pricing(id),
  reason            text
);

CREATE VIEW legacy_pricing_v AS SELECT product_id, region, price FROM legacy_pricing;

-- 58 bytes, so "<name>__<action_id>" (90 bytes) can't fit in 63.
CREATE TABLE "quarterly_revenue_snapshots_by_region_and_sales_channel_v2" (
  id     integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  region text NOT NULL,
  amount numeric(14,2) NOT NULL
);
CREATE INDEX quarterly_rev_region_idx ON "quarterly_revenue_snapshots_by_region_and_sales_channel_v2" (region);

